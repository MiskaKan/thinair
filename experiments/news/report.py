def _headlines(result, pre):
    """The findings, in the order of how much they cost to get."""
    out = []
    rho = (result["orders"]["listwise_vs_input_order"] or (None,))[0]
    if rho is not None and rho >= 0.8:
        out.append(
            f"**One call bought the sharpest negative result.** The listwise "
            f"ordering path returned a valid permutation that reproduced the "
            f"order it was shown (ρ = {rho} against presentation order). It "
            f"passed its law and measured nothing. §7.")
    effects = {a: r for a, r in result["order_effect"].items() if r["same_sign"]}
    if effects:
        worst = max(effects.items(), key=lambda kv: abs(kv[1]["mean"]))
        out.append(
            f"**The instrument reads an axis differently depending on what it "
            f"read first.** On `{worst[0]}`, every base/twin disagreement went "
            f"the same way ({worst[1]['mean']:+.2f} mean shift, "
            f"{worst[1]['moved']} of {worst[1]['n']} items). A context effect, "
            f"not variance: repetition will not average it away. §2.")
    stuck = [(i, a) for i in IDS for a in strategy.AXES
             if (result["matrix"][i].get(a) or {}).get("vetoed")]
    out.append(
        "**A grounding validator pulled the instrument toward wrong answers.** "
        "On the three items whose true count is not printed in them, "
        "`TokenSubset` refused "
        "one and let two through at numbers that were printed in the text but "
        "were not the answer (14 for 16, 340 for 385). Confident, validated, "
        "wrong. §6.")
    sep = result["p_separation"]
    working = [a for a, r in sep.items()
               if (r["separation"] or 0) >= 0.2]
    asleep = [a for a, r in sep.items()
              if r["separation"] is not None and r["separation"] < 0.1]
    if working or asleep:
        out.append(
            "**The stated `p` is a real signal on one axis and a formality on "
            "another.** It separated hits from misses on "
            + ", ".join(f"`{a}`" for a in working) + " and not on "
            + ", ".join(f"`{a}`" for a in asleep) +
            ". Calibration is per axis; a pooled figure would have hidden "
            "both. §5.")
    country = result["concordance"].get("country", {})
    if country.get("hits") == country.get("n"):
        out.append(
            f"**A validator can be the thing that is wrong.** `isoCountry` "
            f"scored four correct readings at zero, because the vendored "
            f"table holds 35 countries. Concordance on that axis was "
            f"{country['hits']}/{country['n']}. §6.")
    if pre and pre.get("near_duplicates"):
        out.append(
            "**The zero-call pass earned its keep.** A wrong dateline "
            "weekday, a duplicate pair, and the coverage limits of the "
            "reference table — all before a single call, and all by "
            "mechanisms genuinely unlike the model's. §1.")
    return out


def _grades(result, pre):
    rows = []
    rows.append(("The `n11`/`n12` duplicate pair", "calibrated",
                 "two classical signals of different mechanism agreed; "
                 "verifiable by inspection with no model in the loop"))
    rows.append(("`n05`'s dateline weekday is wrong", "calibrated",
                 "pure computation against the proleptic Gregorian calendar"))
    ratio = result["laws"].get("ratio_claim", {})
    calc = next((v for k, v in ratio.items() if k.startswith("calculator")), None)
    if calc:
        caught = {i for i, _p, _r in calc["below"]}
        # Restated from corpus.py's docstring, which is unchanged since the
        # pre-registration hash was taken.
        planted = {"n05": "30% stated where 60000/250000 = 24%",
                   "n07": "an average of 420 stated where 4200/11 = 381.8"}
        rows.append((f"Arithmetic fault found in "
                     f"{', '.join(sorted(caught)) or 'no item'} "
                     f"({len(caught)} of {len(planted)} planted)",
                     "calibrated",
                     "adjudicated by `calculate`, not by the instrument, "
                     "which only transcribed the claim"))
        for item_id, what in sorted(planted.items()):
            if item_id not in caught:
                rows.append((f"`{item_id}`'s planted fault ({what}) was "
                             f"**missed**", "n/a",
                             "not a judgement error — the cell never "
                             "resolved, so `Calculator` was never handed a "
                             "claim to check. A law cannot fire on a reading "
                             "that does not exist, and an unresolved cell is "
                             "therefore a silent gap in coverage rather than "
                             "a clean negative"))
    for axis in strategy.GROUNDED:
        row = result["concordance"][axis]
        rate = row["rate"]
        rows.append((f"`{axis}` read at {rate[0]:.0%} concordance"
                     if rate else f"`{axis}` concordance",
                     "calibrated",
                     "measured against a frozen human assignment; interval "
                     f"[{rate[1]:.2f}, {rate[2]:.2f}] on n={row['n']}"
                     if rate else "no readings"))
    rows.append(("Any ordering of the twelve items", "claim",
                 "no ground exists for `follow_up`; the paths that agree "
                 "share mechanism and exposure, so their agreement is cheap"))
    rows.append(("`severity` readings", "claim",
                 "no ground, one model family, and the axis is a judgement "
                 "the corpus cannot settle"))
    return rows


